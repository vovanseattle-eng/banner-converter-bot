from enum import StrEnum


class E(StrEnum):
    SETTINGS   = "5870982283724328568"  # ⚙️ Настройки
    CHECK      = "5870633910337015697"  # ✅ Галочка
    CROSS      = "5870657884844462243"  # ❌ Крестик
    EDIT       = "5870676941614354370"  # 🖋 Перо / вотермарка
    BRUSH      = "6050679691004612757"  # 🖌 Кисть / палитра
    RESIZE     = "5778479949572738874"  # ↔️ Разрешение
    APPS       = "5778672437122045013"  # 📦 3D / эффекты
    SEND       = "5963103826075456248"  # ⬆️ Отправить / входной поток
    FORWARD    = "5963103826075456248"  # ⬆️ Стрелка
    MEDIA      = "6035128606563241721"  # 🖼 Медиа / холст
    PHOTO      = "6035128606563241721"  # 🖼 Фото
    FILE       = "5870528606328852614"  # 📁 Заметки / файлы
    DESIGN     = "5346044461614924803"  # 💎 Алмаз / цвет эмодзи
    FIRE       = "5346168178147880052"  # 🔥 Огонь / заголовок
    SPARKLE    = "5345786042022651125"  # ✨ Искры / элементы
    LOADING    = "5345906554510012647"  # 🔄 Загрузка
    CODE       = "5940433880585605708"  # 💻 Код
    INFO       = "6028435952299413210"  # ℹ️ Инфо


_FALLBACK = {
    E.SETTINGS: "⚙️",
    E.CHECK: "✅",
    E.CROSS: "❌",
    E.EDIT: "🖋",
    E.BRUSH: "🖌",
    E.RESIZE: "↔️",
    E.APPS: "📦",
    E.SEND: "⬆️",
    E.FORWARD: "⬆️",
    E.MEDIA: "🖼",
    E.PHOTO: "🖼",
    E.FILE: "📁",
    E.DESIGN: "💎",
    E.FIRE: "🔥",
    E.SPARKLE: "✨",
    E.LOADING: "🔄",
    E.CODE: "💻",
    E.INFO: "ℹ️",
}


def em(e: E, fallback: str | None = None) -> str:
    """HTML-тег анимированного премиум-эмодзи."""
    fb = fallback or _FALLBACK.get(e, "✨")
    return f'<tg-emoji emoji-id="{e}">{fb}</tg-emoji>'


def title(e: E, text: str) -> str:
    """Жирный заголовок с анимированным премиум-эмодзи."""
    return f"<b>{em(e)} {text}</b>"
